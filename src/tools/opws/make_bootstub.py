"""Generate rtl/ws/swanbios.vhd and rtl/ws/swanbioscolor.vhd: an open replacement for the
WonderSwan / WonderSwan Color boot ROM (the Bandai IPL is copyrighted and not included).

The stub skips the boot logo: it sets up a stack, copies a 7-byte trampoline into
internal RAM, and jumps there; the trampoline sets port 0xA0 bit 0 (which unmaps the
boot ROM) and jumps to the cartridge entry point FFFF:0000."""

STUB_BASE = 0xFFF00          # linear address of the main stub code
code = bytes([
    0xFA,                               # cli
    0x31, 0xC0,                         # xor ax,ax
    0x8E, 0xD0,                         # mov ss,ax
    0xBC, 0x00, 0x20,                   # mov sp,0x2000
    0x8E, 0xD8,                         # mov ds,ax
    0xC7, 0x06, 0x00, 0x01, 0xE6, 0xA0, # mov word [0x100],0xA0E6   out 0xA0,al
    0xC7, 0x06, 0x02, 0x01, 0xEA, 0x00, # mov word [0x102],0x00EA   jmp far ...
    0xC7, 0x06, 0x04, 0x01, 0x00, 0xFF, # mov word [0x104],0xFF00   ... FFFF:0000
    0xC6, 0x06, 0x06, 0x01, 0xFF,       # mov byte [0x106],0xFF
    0xE4, 0xA0,                         # in al,0xA0
    0x0C, 0x01,                         # or al,1
    0xEA, 0x00, 0x01, 0x00, 0x00,       # jmp far 0000:0100
])
reset = bytes([0xEA, 0x00, 0xFF, 0x00, 0xF0])   # at FFFF0: jmp far F000:FF00

img = bytearray([0x90] * 256)                   # linear FFF00..FFFFF
img[0:len(code)] = code
img[0xF0:0xF0 + len(reset)] = reset
words = [img[2 * i] | (img[2 * i + 1] << 8) for i in range(128)]

def vhdl(entity, abits):
    hi = abits - 1
    rows = '\n'.join('         when %3d => data <= x"%04X";' % (i, w) for i, w in enumerate(words) if w != 0x9090)
    return f'''-- Generated by tools/make_bootstub.py: open boot stub (no Bandai IPL), see that script.
library IEEE;
use IEEE.std_logic_1164.all;
use IEEE.numeric_std.all;

entity {entity} is
   port
   (
      clk         : in std_logic;
      address     : in std_logic_vector({hi} downto 0);
      data        : out std_logic_vector(15 downto 0);
      bios_wraddr : in  std_logic_vector({hi} downto 0);
      bios_wrdata : in  std_logic_vector(15 downto 0);
      bios_wr     : in  std_logic
   );
end entity;

architecture arch of {entity} is
begin
   process (clk)
   begin
      if rising_edge(clk) then
         data <= x"9090";
         if address({hi} downto 7) = ({hi} downto 7 => '1') then
            case to_integer(unsigned(address(6 downto 0))) is
{rows}
               when others => data <= x"9090";
            end case;
         end if;
      end if;
   end process;
end architecture;
'''

open('rtl/ws/swanbios.vhd', 'w').write(vhdl('swanbios', 11))
open('rtl/ws/swanbioscolor.vhd', 'w').write(vhdl('swanbioscolor', 12))
print('boot stub: %d bytes code' % len(code))
